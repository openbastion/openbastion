#!/bin/sh
# Creates supplemental recording credentials without changing an existing installation's .env:
#   deploy/docker-compose/init-recording.sh [base-env] [recording-env]
set -eu
script_dir=$(dirname "$0")
base_env="${1:-$script_dir/.env}"
out="${2:-$script_dir/.env.recording}"
keys="PG_PASSWORD_VIDEO_RECORDER VIDEO_RECORDER_S3_ACCESS_KEY VIDEO_RECORDER_S3_SECRET_KEY"

if [ ! -f "$base_env" ]; then
  echo "init-recording.sh: $base_env does not exist — run init.sh first" >&2
  exit 1
fi

base_count=0
for key in $keys; do
  count=$(awk -F= -v key="$key" '$1 == key { count++ } END { print count + 0 }' "$base_env")
  if [ "$count" -gt 1 ]; then
    echo "init-recording.sh: duplicate $key in $base_env; refusing to guess" >&2
    exit 1
  fi
  base_count=$((base_count + count))
done
if [ "$base_count" -eq 3 ]; then
  if [ -e "$out" ]; then
    echo "init-recording.sh: both environment files contain recording credentials; refusing ambiguity" >&2
    exit 1
  fi
  echo "init-recording.sh: recording credentials already exist in $base_env; no file changed"
  exit 0
fi
if [ "$base_count" -ne 0 ]; then
  echo "init-recording.sh: only some recording credentials exist in $base_env; refusing to guess" >&2
  exit 1
fi

if [ -e "$out" ]; then
  out_count=0
  for key in $keys; do
    count=$(awk -F= -v key="$key" '$1 == key { count++ } END { print count + 0 }' "$out")
    if [ "$count" -gt 1 ]; then
      echo "init-recording.sh: duplicate $key in $out; refusing to guess" >&2
      exit 1
    fi
    out_count=$((out_count + count))
  done
  if [ "$out_count" -eq 3 ]; then
    echo "init-recording.sh: $out already contains recording credentials; leaving it unchanged"
    exit 0
  fi
  echo "init-recording.sh: $out already exists but is incomplete; refusing to overwrite it" >&2
  exit 1
fi

hex32() { od -An -N32 -tx1 /dev/urandom | tr -d ' \n'; }
umask 077
tmp="${out}.tmp.$$"
if ! (set -C; : > "$tmp") 2>/dev/null; then
  echo "init-recording.sh: cannot create temporary file $tmp" >&2
  exit 1
fi
trap 'rm -f "$tmp"' EXIT
trap 'exit 1' HUP INT TERM
{
  echo "# Video Recorder credentials — generated by init-recording.sh."
  echo "PG_PASSWORD_VIDEO_RECORDER=$(hex32)"
  echo "VIDEO_RECORDER_S3_ACCESS_KEY=$(hex32)"
  echo "VIDEO_RECORDER_S3_SECRET_KEY=$(hex32)"
} > "$tmp"
chmod 600 "$tmp"
if ! ln "$tmp" "$out" 2>/dev/null; then
  echo "init-recording.sh: could not create $out; it may already exist" >&2
  exit 1
fi
rm -f "$tmp"
trap - EXIT HUP INT TERM
echo "init-recording.sh: recording credentials written to $out (mode 0600); existing files were not changed"
